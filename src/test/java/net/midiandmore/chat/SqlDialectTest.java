public class SqlDialectTest {
    @Test
    public void defaultsToSqliteWhenDatabaseTypeIsMissing() {
        assertEquals(SqlDialect.Type.SQLITE, SqlDialect.Type.fromConfig(null));
        assertEquals(SqlDialect.Type.SQLITE, SqlDialect.Type.fromConfig(""));
        assertEquals(SqlDialect.Type.SQLITE, SqlDialect.Type.fromConfig("  "));
    }

    @Test
    public void sqliteProfilePictureRoundTripPreservesMixedCaseNick() throws Exception {
        try (var connection = DriverManager.getConnection("jdbc:sqlite::memory:");
             var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE test_users (nick TEXT, nick2 TEXT, image_upload BLOB, image_url TEXT)");
            statement.execute("INSERT INTO test_users (nick, nick2) VALUES ('tester', 'Tester')");
            statement.execute("INSERT INTO test_users (nick, nick2) VALUES ('other', 'Other')");
            var database = new Database(null);
            setDatabaseField(database, "prefix", "test_");
            database.setCon(connection);
            byte[] picture = {0, 1, 2, (byte) 255};
            database.updatePicture("Tester", new ByteArrayInputStream(picture), "image/png");
            assertArrayEquals(picture, database.getPicture("Tester"));
            assertArrayEquals(picture, database.getPicture("tester"));
            assertArrayEquals(picture, database.getPicture("TESTER"));
            assertNull(database.getPicture("Other"));
            assertNull(database.getPicture("missing"));
            assertEquals("image/png", database.getData("Tester", "image_url"));
            byte[] replacement = {3, 4, 5};
            database.updatePicture("Tester", new ByteArrayInputStream(replacement), "image/jpeg");
            assertArrayEquals(replacement, database.getPicture("Tester"));
            assertEquals("image/jpeg", database.getData("Tester", "image_url"));
            database.setCon(null);
        }
    }

    @Test
    public void translatesAndExecutesSqliteSchemaAndPasswordHashing() throws Exception {
        try (var raw = DriverManager.getConnection("jdbc:sqlite::memory:")) {
            SqlDialect.initialize(raw, SqlDialect.Type.SQLITE);
            try (var connection = SqlDialect.wrap(raw, SqlDialect.Type.SQLITE);
                 var statement = connection.createStatement()) {
                statement.executeUpdate("CREATE TABLE `stats_hourly` (`id` bigint(20) NOT NULL AUTO_INCREMENT, `hour_bucket` datetime NOT NULL, `room` varchar(255) NOT NULL, `messages` int(11) NOT NULL DEFAULT 0, PRIMARY KEY (`id`), UNIQUE KEY `hour_room` (`hour_bucket`, `room`(100))) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
                try (var insert = connection.prepareStatement("INSERT INTO `stats_hourly` (`hour_bucket`, `room`, `messages`) VALUES (?, ?, SHA2(?,512))")) {
                    insert.setString(1, "2026-11-11 14:00:00");
                    insert.setString(2, "Lounge");
                    insert.setString(3, "test-password");
                    insert.executeUpdate();
                }
                try (var result = statement.executeQuery("SELECT `messages` FROM `stats_hourly`")) {
                    assertTrue(result.next());
                    assertEquals(sha512("test-password"), result.getString(1));
                }
            }
        }
    }

    @Test
    public void translatesPostgresqlSchemaAndPasswordHashing() throws Exception {
        var translated = SqlDialect.translate(
                "CREATE TABLE `users` (`id` bigint(20) NOT NULL AUTO_INCREMENT, `user` varchar(255) NOT NULL, `joined` datetime NOT NULL, PRIMARY KEY (`id`), UNIQUE KEY `user_name` (`user`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci",
                SqlDialect.Type.POSTGRESQL);
        assertTrue(translated.contains("\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY"));
        assertTrue(translated, translated.contains("\"user\" varchar(255)"));
        assertTrue(translated, translated.contains("UNIQUE (\"user\")"));
        assertTrue(translated.contains("\"joined\" TIMESTAMP"));
        assertTrue(SqlDialect.translate("SELECT SHA2(?,512)", SqlDialect.Type.POSTGRESQL)
                .contains("digest(convert_to(?, 'UTF8'), 'sha512')"));
    }

    @Test
    public void initializesFullSqliteSetupSchemaAndSeedData() throws Exception {
        var directory = Files.createTempDirectory("hwebchat-sqlite-test");
        var databaseFile = directory.resolve("chat.sqlite");
        try {
            var setup = new SetupServlet();
            invokeSetup(setup, "createDatabaseTables", new Class<?>[]{
                SqlDialect.Type.class, String.class, String.class, String.class, String.class, String.class, String.class, String.class
            }, SqlDialect.Type.SQLITE, null, null, null, null, null, databaseFile.toString(), "test_");
            invokeSetup(setup, "createFirstUser", new Class<?>[]{
                SqlDialect.Type.class, String.class, String.class, String.class, String.class, String.class, String.class,
                String.class, String.class, String.class, String.class
            }, SqlDialect.Type.SQLITE, null, null, null, null, null, databaseFile.toString(), "test_", "Tester", "test-password", "tester@example.test");
            invokeSetup(setup, "createDefaultRooms", new Class<?>[]{
                SqlDialect.Type.class, String.class, String.class, String.class, String.class, String.class, String.class, String.class
            }, SqlDialect.Type.SQLITE, null, null, null, null, null, databaseFile.toString(), "test_");

            try (var connection = DriverManager.getConnection("jdbc:sqlite:" + databaseFile);
                 var statement = connection.createStatement();
                 var tables = statement.executeQuery("SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name LIKE 'test_%'")) {
                assertTrue(tables.next());
                assertEquals(17, tables.getInt(1));
            }
            try (var connection = DriverManager.getConnection("jdbc:sqlite:" + databaseFile);
                 var statement = connection.createStatement()) {
                try (var users = statement.executeQuery("SELECT LENGTH(pwd) FROM test_users")) {
                    assertTrue(users.next());
                    assertEquals(128, users.getInt(1));
                }
                try (var rooms = statement.executeQuery("SELECT COUNT(*) FROM test_roomcfg")) {
                    assertTrue(rooms.next());
                    assertEquals(4, rooms.getInt(1));
                }
            }
            var database = new Database(null);
            setDatabaseField(database, "databaseType", SqlDialect.Type.SQLITE);
            setDatabaseField(database, "sqlitePath", databaseFile.toString());
            setDatabaseField(database, "prefix", "test_");
            try (var connection = DriverManager.getConnection("jdbc:sqlite:" + databaseFile)) {
                database.setCon(connection);
                database.migrateDatabase();
                database.checkAndCreateMissingProfileColumns();
                database.createGuestbookTable();
                database.upsertHourly("", 2, 2, 10);
                database.upsertHourly("", 4, 4, 12);
                assertTrue(database.addThread("Topic", "Message", 0, 1, 1, "127.0.0.1", 1) > 0);
                var hourly = database.getStatsHourly();
                assertEquals(1, hourly.size());
                assertEquals(3, hourly.get(0).get("avg_users"));
                assertEquals(12, hourly.get(0).get("messages"));
                database.setCon(null);
            }
        } finally {
            Files.deleteIfExists(databaseFile);
            Files.deleteIfExists(directory);
        }
    }

    private void invokeSetup(SetupServlet setup, String methodName, Class<?>[] parameterTypes, Object... args) throws Exception {
        Method method = SetupServlet.class.getDeclaredMethod(methodName, parameterTypes);
        method.setAccessible(true);
        method.invoke(setup, args);
    }

    private void setDatabaseField(Database database, String fieldName, Object value) throws Exception {
        var field = Database.class.getDeclaredField(fieldName);
        field.setAccessible(true);
        field.set(database, value);
    }

    private String sha512(String value) throws Exception {
        var digest = MessageDigest.getInstance("SHA-512").digest(value.getBytes(StandardCharsets.UTF_8));
        var hex = new StringBuilder(digest.length * 2);
        for (var item : digest) {
            hex.append(String.format("%02x", item & 0xff));
        }
        return hex.toString();
    }
}
